def main():
    model = llm.pick_model()
    print('модель', model)
    items = [{'id': str(i), 'type': t, 'value': v, 'snippet': ctx} for i, (t, v, ctx, _) in enumerate(CASES)]
    t0 = time.time()
    removed = set(llm.review(items, model))
    good = bad = 0
    for i, (t, v, ctx, should) in enumerate(CASES):
        got = str(i) in removed
        ok = got == should
        good += ok and should
        bad += got and not should
        print(('✓ ' if ok else '✗ ') + ('снять   ' if should else 'оставить') + '  %s «%s»%s' % (t, v, '' if ok else ('  — сняла зря' if got else '  — не сняла')))
    need = sum(1 for c in CASES if c[3])
    print('Снято лишнего %d из %d, снято зря %d, %.1f с' % (good, need, bad, time.time() - t0))


if __name__ == '__main__':
    main()
