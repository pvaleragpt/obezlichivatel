def main():
    model = llm.pick_model()
    print('модель', model)
    need = hit = fp = 0
    t0 = time.time()
    for text, must, must_not in CASES:
        got = [it['text'] for it in llm.detect([text], model)[0]]
        miss = [m for m in must if not any(m in g or g in m for g in got)]
        bad = [n for n in must_not if any(n in g for g in got)]
        need += len(must); hit += len(must) - len(miss); fp += len(bad)
        print(('✓ ' if not miss and not bad else '✗ ') + text[:70] + ('  пропущено: ' + ', '.join(miss) if miss else '') + ('  лишнее: ' + ', '.join(bad) if bad else ''))
    print('Найдено %d из %d, лишнего %d, %.1f с на фразу' % (hit, need, fp, (time.time() - t0) / len(CASES)))


if __name__ == '__main__':
    main()
